"""Generated appendices of the copilot evaluation report: the claims ledger and the software table.

texgen.main() calls render_all() when REPORT_DOC=copilot, in place of the Atlas report's appendices (which describe
notebooks and country tables this document does not use). The claims ledger is the Atlas report's, unchanged.
"""

from __future__ import annotations

from pathlib import Path

from report_lib.appendix import _first_line, _git, claims_ledger, locked_versions, longtable
from report_lib.manifest import Claim
from report_lib.paths import GENERATED, REPO, REPORT
from report_lib.texgen import tex_escape

# Packages whose versions decide a number in the evaluations or in this report.
PACKAGES = (
    "duckdb", "matplotlib", "numpy", "optuna", "pandas", "pydantic", "pylatexenc", "scikit-learn", "scipy",
    "sentence-transformers", "statsmodels", "torch", "transformers",
)  # fmt: skip


def software() -> dict[str, str]:
    report, copilot = (
        locked_versions(REPORT / "uv.lock"),
        locked_versions(REPO / "copilot" / "uv.lock"),
    )
    tools = [
        ("TeX engine", _first_line(["pdftex", "--version"])),
        ("Bibliography", _first_line(["biber", "--version"])),
        ("Build driver", _first_line(["latexmk", "-v"]).strip("- ")),
    ]
    rows = [f"{tex_escape(k)} & \\multicolumn{{2}}{{l}}{{{tex_escape(v)}}} \\\\" for k, v in tools]
    rows.append(r"\midrule")
    for name in PACKAGES:
        rows.append(
            f"\\texttt{{{name}}} & {copilot.get(name, '--')} & {report.get(name, '--')} \\\\"
        )
    toolchain = longtable("@{}lll@{}", ["Component", "copilot", "report"], rows,
                          "Toolchain and the versions of the packages that compute or typeset a number, as the lock "
                          "files resolve them on the platform this copy was built on. The evaluations ran in the "
                          "copilot environment; this report's statistics and figures in the report environment.",
                          "app-software")  # fmt: skip
    head = _git("rev-parse", "--short", "HEAD")
    dirty = (
        " with uncommitted changes"
        if _git("status", "--porcelain", "--", "report", "copilot")
        else ""
    )
    prov = [("Report built from commit", head + dirty)]
    prov_rows = [f"{tex_escape(k)} & \\texttt{{{tex_escape(v)}}} \\\\" for k, v in prov]
    provenance = longtable("@{}ll@{}", ["Record", "Value"], prov_rows, "Provenance of this build.",
                           "app-provenance")  # fmt: skip
    return {"software-toolchain": toolchain, "software-provenance": provenance}


def render_all(claims: dict[str, Claim], out_dir: Path = GENERATED) -> list[Path]:
    target = out_dir / "appendices"
    target.mkdir(parents=True, exist_ok=True)
    written = []
    for name, text in {"claims": claims_ledger(claims), **software()}.items():
        path = target / f"{name}.tex"
        path.write_text(f"% Generated by report_lib.copilot_appendix. Do not edit.\n{text}")
        written.append(path)
    return written
