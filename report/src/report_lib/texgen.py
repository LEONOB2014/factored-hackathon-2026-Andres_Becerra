"""Generate the LaTeX the chapters read: claims (\\est), protocol constants (\\proto) and tables.

    uv run python -m report_lib.texgen

Fails when a chapter references an \\est id or field that no claim defines, or a \\proto key that the protocol
does not define.
"""

from __future__ import annotations

import csv
import math
import re
import sys
from pathlib import Path

import pandas as pd

from report_lib import claims as claims_mod
from report_lib import protocol, sources
from report_lib.manifest import Claim
from report_lib.paths import CLAIMS_DIR, GENERATED, TEX
from report_lib.privacy import check_frame

EST_REF = re.compile(r"\\est\{([^}]*)\}\{([^}]*)\}")
PROTO_REF = re.compile(r"\\proto\{([^}]*)\}")
TABLE_MANIFEST = "tables/manifest.csv"


def num(v: float, digits: int | None = None) -> str:
    """A number for siunitx: integers exactly, other values to `digits` significant figures (default 3)."""
    if float(v).is_integer() and abs(v) < 1e15:
        return f"\\num{{{int(v)}}}"
    d = digits or 3
    return f"\\num{{{float(f'{v:.{d}g}')!r}}}"


def tex_escape(s: str) -> str:
    repl = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_",
            "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}  # fmt: skip
    math = {"χ": r"\ensuremath{\chi}", "²": r"\textsuperscript{2}", "×": r"\ensuremath{\times}",
            "±": r"\ensuremath{\pm}", "≤": r"\ensuremath{\le}", "≥": r"\ensuremath{\ge}", "−": r"\ensuremath{-}",
            "µ": r"\ensuremath{\mu}", "≈": r"\ensuremath{\approx}"}  # fmt: skip
    return "".join(repl.get(ch, math.get(ch, ch)) for ch in s)


def claim_fields(c: Claim) -> dict[str, str]:
    """Every field a chapter may cite with \\est{id}{field}."""
    out: dict[str, str] = {}
    for f in ("value", "estimate", "num", "den", "events", "exposure", "lo", "hi", "se", "statistic", "df",
              "p", "q", "family_size", "n"):  # fmt: skip
        v = getattr(c, f)
        if v is not None:
            out[f] = num(v, c.digits)
    for f in ("interval_method", "cluster_unit", "family_id", "method", "unit", "status", "null"):
        v = getattr(c, f)
        if v is not None:
            out[f] = tex_escape(str(v))
    if c.lo is not None and c.hi is not None:
        mark = r"\naivemark" if c.interval_method == "naive-iid" else ""
        out["ci"] = f"[{num(c.lo, c.digits)}, {num(c.hi, c.digits)}]{mark}"
    if c.kind == "proportion":
        out["share"] = num(c.num / c.den, c.digits)
        out["pct"] = num(100 * c.num / c.den, c.digits)
        out["pct_lo"] = num(100 * c.lo, c.digits)
        out["pct_hi"] = num(100 * c.hi, c.digits)
        mark = r"\naivemark" if c.interval_method == "naive-iid" else ""
        out["pct_ci"] = f"[{out['pct_lo']}, {out['pct_hi']}]{mark}"
    return out


def render_claims(all_claims: dict[str, Claim]) -> tuple[str, dict[str, set[str]]]:
    lines = ["% Generated by report_lib.texgen from build/claims/*.parquet. Do not edit."]
    defined: dict[str, set[str]] = {}
    for cid in sorted(all_claims):
        fields = claim_fields(all_claims[cid])
        defined[cid] = set(fields)
        for f, v in sorted(fields.items()):
            lines.append(f"\\expandafter\\def\\csname est@{cid}@{f}\\endcsname{{{v}}}")
    return "\n".join(lines) + "\n", defined


def render_protocol(proto: dict) -> tuple[str, set[str]]:
    lines = ["% Generated by report_lib.texgen from conf/protocol.toml. Do not edit."]
    keys = set()
    for k, v in sorted(protocol.flatten(proto).items()):
        if isinstance(v, bool):
            val = "true" if v else "false"
        elif isinstance(v, int | float):
            if isinstance(v, float) and not math.isfinite(v):
                raise ValueError(f"protocol key {k} is not finite")
            val = num(v)
        elif isinstance(v, list):
            val = ", ".join(num(x) if isinstance(x, int | float) else tex_escape(str(x)) for x in v)
            keys.add(f"{k}.n")
            lines.append(f"\\expandafter\\def\\csname proto@{k}.n\\endcsname{{{num(len(v))}}}")
        else:
            val = tex_escape(str(v))
        keys.add(k)
        lines.append(f"\\expandafter\\def\\csname proto@{k}\\endcsname{{{val}}}")
    return "\n".join(lines) + "\n", keys


def chapter_files(tex: Path = TEX) -> list[Path]:
    return sorted(
        [*tex.glob("chapters/*.tex"), *tex.glob("appendices/*.tex"), *tex.glob("frontmatter/*.tex")]
    )


def unresolved(files: list[Path], defined: dict[str, set[str]], proto_keys: set[str]) -> list[str]:
    problems = []
    for path in files:
        text = re.sub(r"(?<!\\)%.*", "", path.read_text())
        for cid, field in EST_REF.findall(text):
            if cid not in defined:
                problems.append(f"{path.name}: \\est{{{cid}}} has no claim")
            elif field not in defined[cid]:
                problems.append(f"{path.name}: claim {cid} has no field {field!r}")
        for key in PROTO_REF.findall(text):
            if key not in proto_keys:
                problems.append(f"{path.name}: \\proto{{{key}}} is not in protocol.toml")
    return problems


def render_table(
    source: Path,
    label: str,
    caption: str,
    columns: list[str] | None = None,
    count_cols: list[str] | tuple[str, ...] = (),
    digits: int = 3,
    out_dir: Path = GENERATED,
    min_cell: int | None = None,
) -> Path:
    """Render one CSV source as a booktabs table whose caption carries the source path and its SHA-256."""
    if not re.fullmatch(r"[a-z0-9][a-z0-9-]*", label):
        raise ValueError(f"table label {label!r} must be lowercase letters, digits and hyphens")
    frame = pd.read_csv(source)
    if columns:
        frame = frame[columns]
    min_cell = min_cell if min_cell is not None else int(protocol.load()["privacy"]["min_cell"])
    check_frame(frame, min_cell, count_cols)
    digest = sources.sha256(source)
    rel = sources.rel(source)
    spec = "".join("r" if pd.api.types.is_numeric_dtype(frame[c]) else "l" for c in frame.columns)
    head = " & ".join(tex_escape(str(c).replace("_", " ")) for c in frame.columns)
    body = []
    for row in frame.itertuples(index=False):
        cells = []
        for v in row:
            if isinstance(v, int | float) and not isinstance(v, bool) and pd.notna(v):
                cells.append(num(float(v), digits))
            else:
                cells.append("" if pd.isna(v) else tex_escape(str(v)))
        body.append(" & ".join(cells) + r" \\")
    tex = "\n".join([
        f"% Generated by report_lib.texgen from {rel} (sha256 {digest}). Do not edit.",
        r"\begin{table}[htbp]\centering\small",
        f"\\caption{{{caption} Source: \\texttt{{{tex_escape(rel)}}}, SHA-256 \\texttt{{{digest[:12]}}}.}}",
        f"\\label{{tab:{label}}}",
        f"\\fittable{{\\begin{{tabular}}{{{spec}}}", r"\toprule", head + r" \\", r"\midrule", *body, r"\bottomrule",
        r"\end{tabular}}", r"\end{table}",
    ])  # fmt: skip
    tables = out_dir / "tables"
    tables.mkdir(parents=True, exist_ok=True)
    path = tables / f"{label}.tex"
    path.write_text(tex + "\n")
    _record_table(out_dir / TABLE_MANIFEST, label, rel, digest)
    return path


def _record_table(manifest: Path, label: str, rel: str, digest: str) -> None:
    rows = {}
    if manifest.exists():
        with manifest.open() as f:
            rows = {r["label"]: r for r in csv.DictReader(f)}
    rows[label] = {"label": label, "source_path": rel, "sha256": digest}
    with manifest.open("w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=["label", "source_path", "sha256"])
        w.writeheader()
        w.writerows(rows[k] for k in sorted(rows))


def main(claims_dir: Path = CLAIMS_DIR, out_dir: Path = GENERATED) -> int:
    out_dir.mkdir(parents=True, exist_ok=True)
    all_claims = claims_mod.load_all(claims_dir)
    claims_tex, defined = render_claims(all_claims)
    proto_tex, keys = render_protocol(protocol.load())
    (out_dir / "claims.tex").write_text(claims_tex)
    (out_dir / "protocol.tex").write_text(proto_tex)
    problems = unresolved(chapter_files(), defined, keys)
    for p in problems:
        print(p, file=sys.stderr)
    print(
        f"{len(all_claims)} claims, {len(keys)} protocol keys, {len(problems)} unresolved references"
    )
    return 1 if problems else 0


if __name__ == "__main__":
    raise SystemExit(main())
